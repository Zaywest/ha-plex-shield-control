#!/bin/sh
# Combines the two cards into the single file HACS installs: dist/ha-plex-shield-control.js
# Run after editing anything in cards/.
cd "$(dirname "$0")"
mkdir -p dist
{
  echo "/* ha-plex-shield-control: Plex Library card + Plex Now Playing card."
  echo "   Generated by build-dist.sh from cards/. Edit those files, not this one. */"
  echo
  cat cards/plex-library-card.js
  echo
  echo "{ // plex-now-playing-card"
  cat cards/plex-now-playing-card.js
  echo "}"
} > dist/ha-plex-shield-control.js
echo "built dist/ha-plex-shield-control.js"
